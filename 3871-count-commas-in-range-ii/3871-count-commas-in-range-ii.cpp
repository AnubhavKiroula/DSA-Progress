class Solution {
public:
    long long countCommas(long long n) {
        if(n <= 999){
            return 0;
        }
        else if(n <= 999999){
            return n - 999;
        }
        else if(n <= 999999999){
            return (999999 - 999)
                 + 2 * (n - 999999);
        }
        else if(n <= 999999999999LL){
            return (999999 - 999)
                 + 2 * (999999999 - 999999)
                 + 3 * (n - 999999999);
        }
        else if(n <= 999999999999999LL){
            return (999999 - 999)
                 + 2 * (999999999 - 999999)
                 + 3 * (999999999999LL - 999999999)
                 + 4 * (n - 999999999999LL);
        }
        return (999999 - 999)
            + 2 * (999999999 - 999999)
            + 3 * (999999999999LL - 999999999)
            + 4 * (999999999999999LL - 999999999999LL)
            + 5 * (n - 999999999999999LL);
    }
};